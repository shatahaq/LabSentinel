"""Export the wire protocol as a versioned JSON Schema artifact.

Run after any protocol change:  python scripts/export_schema.py
Writes shared/schema/protocol.v<N>.schema.json so the contract is reviewable in
diffs and consumable by non-Python tooling.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_ROOT / "shared"))

from labsentinel_shared.protocol import PROTOCOL_VERSION, Envelope  # noqa: E402


def main() -> int:
    schema = Envelope.model_json_schema()
    schema["title"] = "LabSentinel Protocol Envelope"
    schema["$comment"] = f"Protocol version {PROTOCOL_VERSION}. Generated by export_schema.py."
    out_dir = _ROOT / "shared" / "schema"
    out_dir.mkdir(parents=True, exist_ok=True)
    out = out_dir / f"protocol.v{PROTOCOL_VERSION}.schema.json"
    out.write_text(json.dumps(schema, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(f"wrote {out.relative_to(_ROOT)} ({out.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
